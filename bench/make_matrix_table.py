"""
The matrix table, generated on its own.

    python bench/make_matrix_table.py --out manuscript/parts/table_5_matrix.tex

Rationale: the matrix is the one table that is assembled from another file
(bench/competitive_matrix.json).  Generating it as a separate .tex file, which the
manuscript inputs, keeps fill_manuscript.py to its actual job - filling the numbers of the
working copy - and makes the generated table readable and diffable on its own.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def _tex(value: str) -> str:
    return (value.replace("&", r"\&").replace("_", r"\_").replace("#", r"\#")
            .replace("%", r"\%"))


def _label(tool: str) -> str:
    return tool.replace(" (this work)", "")


def _short(value: str) -> str:
    low = value.strip().lower()
    for word in ("yes", "no", "partial"):
        if low.startswith(word):
            return word
    return value.strip()


def _mark(value: str) -> str:
    """A mark, not a word: the table is read column by column, not row by row."""
    short = _short(value)
    return {"yes": r"\textbf{yes}", "no": r"--", "partial": r"\emph{part.}"}.get(
        short, _tex(short))


# The capability names are written for the JSON, where they are argument names, and are too
# long for a column of a table that has to be read across.  These are the names of the table.
CAPABILITY_LABELS = {
    "TM_CROSSING": "transmembrane segment",
    "TOPOLOGY": "topology (which side each loop is on)",
    "SIDE": "which side each loop is on",
    "ORIENTATION": "orientation of the protein in the bilayer",
    "PREDICTED": "works on a predicted model",
    "STRUCTURE": "works on the 3-D structure",
    "MEMBRANE_FRAME": "fits the membrane itself",
    "FREE_ENERGY": "reports a free energy of placement",
    "UNROLLING": "two-dimensional unrolling",
    "CONFIDENCE": "per-residue confidence",
    "EXPORT": "machine-readable export",
    "BATCH": "batch runs",
    "WEB": "web interface",
}


def _short_capability(capability: str) -> str:
    if capability in CAPABILITY_LABELS:
        return CAPABILITY_LABELS[capability]
    words = capability.split()
    return " ".join(word if word.isupper() or word[0].isdigit() else word.lower()
                    for word in words)


def matrix_table(matrix: dict) -> str:
    tools = matrix.get("tools", [])
    capabilities = matrix.get("capabilities", [])
    if not tools or not capabilities:
        raise SystemExit("competitive_matrix.json has no tools or no capabilities")
    n = len(tools)
    short = {c: _short_capability(c) for c in capabilities}
    head = (r"\textbf{what the tool can do} & "
            + " & ".join(r"\textbf{%s}" % _tex(_label(t["tool"])) for t in tools) + r" \\")
    body = []
    for capability in capabilities:
        cells = [_tex(short[capability])]
        for tool in tools:
            cells.append(_mark(str(tool["capabilities"].get(capability, "-"))))
        body.append(" & ".join(cells) + r" \\")
    # The caption is a paragraph in its own right: it is set above the table at the width of
    # the text block, and the table itself is a tabularx whose first column takes whatever
    # width is left after the five marked columns.  It is the table's own \caption, not a
    # \captionof, so that the caption numbers, lists and the \pageref of the text all follow
    # the one counter that the float itself uses.
    return "\n".join([
        "% Generated by bench/make_matrix_table.py from bench/competitive_matrix.json.",
        "% Do not edit by hand: edit the JSON and regenerate.",
        r"\begin{table}[!htbp]",
        r"\small",
        r"\caption{What each tool can do. \emph{Yes}: the capability exists in the "
        r"published version; \emph{part.}: it exists only in a limited form, described in the "
        r"text; a dash means that it does not exist. The column heads are the abbreviations "
        r"only; the full citations are in the text. Every entry about a competitor is taken "
        r"from that competitor's own repository or documentation, and the pointers are "
        r"checked when the table is generated.}\label{table:matrix}",
        r"\centering",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\renewcommand{\arraystretch}{1.22}",
        r"\begin{tabularx}{\linewidth}{@{}>{\raggedright\arraybackslash}X*{%d}{c}@{}}"
        % n,
        r"\toprule",
        head,
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table}",
        "",
    ])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--matrix", default="bench/competitive_matrix.json")
    ap.add_argument("--out", default="manuscript/parts/table_5_matrix.tex")
    args = ap.parse_args()
    matrix = json.loads(Path(args.matrix).read_text(encoding="utf-8"))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(matrix_table(matrix), encoding="utf-8")
    print(f"written to {out}")


if __name__ == "__main__":
    main()
